import { afterEach, beforeEach, expect, it, vi } from 'vitest'
const mock = vi.hoisted(() => ({ documents: [{ document: { sessionId: 'a' }, dirty: true, buffer: 'unsaved' }], release: vi.fn() }))
vi.mock('@/stores/goide', () => ({ useGoIDEStore: { getState: () => ({ documents: mock.documents }), subscribe: vi.fn() } }))
vi.mock('./goStudioModelUri', () => ({ releaseDormantModels: mock.release }))
beforeEach(() => { vi.resetModules(); vi.useFakeTimers(); mock.release.mockClear() })
afterEach(() => vi.useRealTimers())

it('keeps visible idle editors, sleeps hidden editors and wakes without changing buffers', async () => {
  const { useActivityStore, IDLE_AFTER_MS } = await import('@/stores/activity')
  const { startGoStudioHibernation, useGoStudioHibernation } = await import('./goStudioHibernation')
  useActivityStore.setState({ phase: 'Idle', scopes: ['goide:a'] })
  startGoStudioHibernation(); startGoStudioHibernation()
  vi.advanceTimersByTime(IDLE_AFTER_MS * 2)
  expect(useGoStudioHibernation.getState().sleeping.a).toBeUndefined()
  useActivityStore.setState({ phase: 'Active', scopes: ['collections'] })
  vi.advanceTimersByTime(IDLE_AFTER_MS)
  vi.advanceTimersByTime(1)
  expect(useGoStudioHibernation.getState().sleeping.a).toBe(true)
  expect(mock.release).toHaveBeenCalledTimes(1)
  expect(mock.documents[0].buffer).toBe('unsaved')
  useActivityStore.setState({ phase: 'Active', scopes: ['goide:a'] })
  expect(useGoStudioHibernation.getState().sleeping.a).toBeUndefined()
  expect(vi.getTimerCount()).toBe(0)
})
