import { afterEach, beforeEach, expect, it, vi } from 'vitest'
import { minuteAlignedTimeout, visibleInterval } from './visiblePolling'
import { pollingDelay, useActivityStore } from '@/stores/activity'
beforeEach(() => {
  vi.useFakeTimers()
  vi.stubGlobal('window', { setTimeout, clearTimeout })
  vi.stubGlobal('document', { hidden: false })
  useActivityStore.setState({ phase: 'Active', scopes: ['goide'], retained: {} })
})
afterEach(() => { vi.useRealTimers(); vi.unstubAllGlobals() })
it('runs active cadence, slows status in Idle, stops in Background, refreshes on resume', () => {
  const callback = vi.fn()
  const stop = visibleInterval(callback, 1000)
  vi.advanceTimersByTime(2000); expect(callback).toHaveBeenCalledTimes(2)
  useActivityStore.getState().setPhase('Idle'); callback.mockClear()
  vi.advanceTimersByTime(14_999); expect(callback).not.toHaveBeenCalled()
  vi.advanceTimersByTime(1); expect(callback).toHaveBeenCalledTimes(1)
  useActivityStore.getState().setPhase('Background'); callback.mockClear()
  expect(vi.getTimerCount()).toBe(0)
  vi.advanceTimersByTime(60_000); expect(callback).not.toHaveBeenCalled()
  useActivityStore.getState().setPhase('Active'); expect(callback).toHaveBeenCalledTimes(1)
  stop(); expect(vi.getTimerCount()).toBe(0)
})
it('stops decorative work in Idle but preserves intentional live status cadence', () => {
  const decoration = vi.fn(), live = vi.fn()
  const stopDecoration = visibleInterval(decoration, 500, { kind: 'decorative' })
  const stopLive = visibleInterval(live, 500, { kind: 'live' })
  useActivityStore.getState().setPhase('Idle'); decoration.mockClear(); live.mockClear()
  vi.advanceTimersByTime(2000)
  expect(decoration).not.toHaveBeenCalled(); expect(live).toHaveBeenCalledTimes(4)
  stopDecoration(); stopLive(); expect(vi.getTimerCount()).toBe(0)
})
it('does not poll a retained panel whose workspace is invisible', () => {
  const callback = vi.fn()
  const stop = visibleInterval(callback, 1000, { scope: 'goide' })
  useActivityStore.getState().setScopes(['collections'])
  vi.advanceTimersByTime(30_000); expect(callback).not.toHaveBeenCalled()
  useActivityStore.getState().setScopes(['goide']); expect(callback).toHaveBeenCalledTimes(1)
  stop()
})
it('cleanup removes timer and store subscription', () => {
  const callback = vi.fn(), stop = visibleInterval(callback, 1000)
  stop(); useActivityStore.getState().setPhase('Idle'); vi.advanceTimersByTime(100_000)
  expect(callback).not.toHaveBeenCalled(); expect(vi.getTimerCount()).toBe(0)
})
it('defines suspended polling as stopped', () => { expect(pollingDelay(500, 'Suspended', 'live')).toBeNull() })
it('keeps a single minute-aligned decorative timer', () => {
  vi.setSystemTime(new Date('2026-10-15T10:30:15Z'))
  const callback = vi.fn(), stop = minuteAlignedTimeout(callback)
  vi.advanceTimersByTime(45_000); expect(callback).toHaveBeenCalledTimes(1)
  vi.advanceTimersByTime(60_000); expect(callback).toHaveBeenCalledTimes(2)
  stop(); expect(vi.getTimerCount()).toBe(0)
})

it('parks the minute clock while idle and updates it on resume', () => {
  const callback = vi.fn(), stop = minuteAlignedTimeout(callback)
  useActivityStore.getState().setPhase('Idle')
  vi.advanceTimersByTime(30 * 60_000)
  expect(callback).not.toHaveBeenCalled(); expect(vi.getTimerCount()).toBe(0)
  useActivityStore.getState().setPhase('Active'); expect(callback).toHaveBeenCalledTimes(1)
  stop()
})
