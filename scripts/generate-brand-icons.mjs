// Extracts the selected Simple Icons (https://simpleicons.org, CC0) into a small
// generated TypeScript module, so the bundle ships only the brands adOmnia uses
// instead of all ~3,400 icons.
//
// Usage: node scripts/generate-brand-icons.mjs <path-to-simple-icons-checkout>
// To add a brand: append its slug (the SVG file name in icons/) to SLUGS and rerun.
import { readFileSync, realpathSync, statSync, writeFileSync } from 'node:fs'
import { join, resolve, sep } from 'node:path'

const SLUGS = [
  'go', 'docker', 'git', 'github', 'githubactions', 'gitlab', 'kubernetes', 'helm', 'terraform',
  'apachekafka', 'rabbitmq', 'mqtt', 'postgresql', 'mysql', 'mariadb', 'mongodb', 'redis', 'sqlite',
  'markdown', 'yaml', 'json', 'xml', 'toml', 'html5', 'css', 'graphql', 'javascript', 'typescript',
  'nodedotjs', 'npm', 'python', 'rust', 'gnubash', 'make', 'dotenv', 'editorconfig', 'prettier',
  'eslint', 'nginx', 'openapiinitiative', 'swagger', 'prometheus', 'grafana', 'renovate', 'dependabot',
  // Linguaggi dell'IDE Platform: ogni language contribution sceglie qui la propria icona.
  'openjdk', 'kotlin', 'php', 'ruby', 'dotnet', 'cplusplus', 'c', 'swift', 'dart', 'scala', 'elixir',
  'haskell', 'lua', 'zig', 'gradle', 'apachemaven', 'fsharp', 'perl', 'r', 'julia', 'clojure',
  'nixos', 'latex', 'ocaml', 'erlang', 'apachegroovy', 'cmake', 'vuedotjs', 'svelte',
  // Agenti AI di Code Studio.
  'claude',
]

const rootArgument = process.argv[2]
if (typeof rootArgument !== 'string' || rootArgument.length === 0 || rootArgument.includes('\0')) {
  console.error('usage: node scripts/generate-brand-icons.mjs <simple-icons checkout>')
  process.exit(1)
}

// The checkout the developer passes on the command line, made absolute and canonicalised with realpath so
// a symlinked root cannot shift under the check. It is used only as the base directory of inRoot(): every
// read goes through inRoot, which allows plain `name.ext` segments and refuses anything that would leave the
// checkout (the slug list below is a constant, but the check does not depend on that).
const resolvedRoot = resolve(rootArgument)
if (!statSync(resolvedRoot, { throwIfNoEntry: false })?.isDirectory()) { // NOSONAR -- the only argv-derived value in the script: it is the base directory the developer names, canonicalised right below and never used for a read outside inRoot()
  console.error(`not a directory: ${resolvedRoot}`)
  process.exit(1)
}
const root = realpathSync(resolvedRoot)

const SAFE_SEGMENT = /^[A-Za-z0-9._-]+$/
function inRoot(...segments) {
  for (const segment of segments) {
    if (!SAFE_SEGMENT.test(segment) || segment.includes('..')) throw new Error(`refusing unsafe path segment: ${segment}`)
  }
  const target = resolve(root, ...segments)
  if (target !== root && !target.startsWith(root + sep)) throw new Error(`refusing to read outside the checkout: ${target}`)
  return target
}

const data = JSON.parse(readFileSync(inRoot('data', 'simple-icons.json'), 'utf8')) // NOSONAR -- constant segments, allowlisted in inRoot and confined to the canonicalised checkout root
const byTitle = new Map(data.map((entry) => [entry.title, entry]))

const icons = SLUGS.map((slug) => {
  if (!/^[a-z0-9-]+$/.test(slug)) throw new Error(`invalid icon slug: ${slug}`)
  const svg = readFileSync(inRoot('icons', `${slug}.svg`), 'utf8') // NOSONAR -- slug is a constant validated above, the path resolves under the canonicalised root and is confined by inRoot()
  const title = svg.match(/<title>([^<]+)<\/title>/)?.[1]
  const path = svg.match(/ d="([^"]+)"/)?.[1]
  const entry = title && byTitle.get(title.replace(/&amp;/g, '&'))
  if (!title || !path || !entry) throw new Error(`icon ${slug}: title, path or metadata not found`)
  return { slug, title: entry.title, hex: entry.hex, path, license: entry.license?.type ?? '' }
})

// Marks Simple Icons does not ship, drawn by adOmnia in the same 24×24 single-path shape. They are
// part of the generated file so a regeneration keeps them.
const CUSTOM = [
  { slug: 'powershell', title: 'PowerShell', hex: '5391FE', path: 'M6 4.5L15 11.4v1.2L6 19.5l-1.6-1.3L12.6 12 4.4 5.8 6 4.5Zm9.3 12h3.4a1.3 1.3 0 0 1 0 2.6h-3.4a1.3 1.3 0 0 1 0-2.6Z' },
  { slug: 'protobuf', title: 'Protocol Buffers', hex: '1EA8FF', path: 'M12 2l9.6 5.6v8.8L12 22l-9.6-5.6V7.6L12 2Zm0 2.2L4.4 8.6v6.8L12 19.8l7.6-4.4V8.6L12 4.2Z' },
]
icons.push(...CUSTOM)

const body = icons.map((icon) => `  ${JSON.stringify(icon.slug)}: { title: ${JSON.stringify(icon.title)}, hex: ${JSON.stringify(icon.hex)}, path: ${JSON.stringify(icon.path)}${icon.license ? `, license: ${JSON.stringify(icon.license)}` : ''} },`).join('\n')

const output = `// GENERATED by scripts/generate-brand-icons.mjs — do not edit by hand.
// Source: Simple Icons (https://github.com/simple-icons/simple-icons), released under CC0-1.0.
// Brand marks remain their owners' trademarks; see the Simple Icons DISCLAIMER and each
// brand's guidelines. Per-icon licenses are listed where Simple Icons records one.
// A few marks Simple Icons does not ship (PowerShell, Protocol Buffers) are drawn by adOmnia.

export interface BrandIconData {
  title: string
  /** Colore ufficiale del marchio, senza #. */
  hex: string
  /** Path SVG su viewBox 0 0 24 24. */
  path: string
  license?: string
}

export const BRAND_ICONS = {
${body}
} as const satisfies Record<string, BrandIconData>

export type BrandIconSlug = keyof typeof BRAND_ICONS
`

const target = join(import.meta.dirname, '..', 'frontend', 'src', 'lib', 'brandIcons.generated.ts')
writeFileSync(target, output)
console.log(`wrote ${icons.length} icons to ${target}`)
