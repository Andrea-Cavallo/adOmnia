// Extracts the selected Simple Icons (https://simpleicons.org, CC0) into a small
// generated TypeScript module, so the bundle ships only the brands adOmnia uses
// instead of all ~3,400 icons.
//
// Usage: node scripts/generate-brand-icons.mjs <path-to-simple-icons-checkout>
// To add a brand: append its slug (the SVG file name in icons/) to SLUGS and rerun.
import { readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

const SLUGS = [
  'go', 'docker', 'git', 'github', 'githubactions', 'gitlab', 'kubernetes', 'helm', 'terraform',
  'apachekafka', 'rabbitmq', 'mqtt', 'postgresql', 'mysql', 'mariadb', 'mongodb', 'redis', 'sqlite',
  'markdown', 'yaml', 'json', 'xml', 'toml', 'html5', 'css', 'graphql', 'javascript', 'typescript',
  'nodedotjs', 'npm', 'python', 'rust', 'gnubash', 'make', 'dotenv', 'editorconfig', 'prettier',
  'eslint', 'nginx', 'openapiinitiative', 'swagger', 'prometheus', 'grafana', 'renovate', 'dependabot',
]

const root = process.argv[2]
if (!root) {
  console.error('usage: node scripts/generate-brand-icons.mjs <simple-icons checkout>')
  process.exit(1)
}

const data = JSON.parse(readFileSync(join(root, 'data', 'simple-icons.json'), 'utf8'))
const byTitle = new Map(data.map((entry) => [entry.title, entry]))

const icons = SLUGS.map((slug) => {
  const svg = readFileSync(join(root, 'icons', `${slug}.svg`), 'utf8')
  const title = svg.match(/<title>([^<]+)<\/title>/)?.[1]
  const path = svg.match(/ d="([^"]+)"/)?.[1]
  const entry = title && byTitle.get(title.replace(/&amp;/g, '&'))
  if (!title || !path || !entry) throw new Error(`icon ${slug}: title, path or metadata not found`)
  return { slug, title: entry.title, hex: entry.hex, path, license: entry.license?.type ?? '' }
})

const body = icons.map((icon) => `  ${JSON.stringify(icon.slug)}: { title: ${JSON.stringify(icon.title)}, hex: ${JSON.stringify(icon.hex)}, path: ${JSON.stringify(icon.path)}${icon.license ? `, license: ${JSON.stringify(icon.license)}` : ''} },`).join('\n')

const output = `// GENERATED by scripts/generate-brand-icons.mjs — do not edit by hand.
// Source: Simple Icons (https://github.com/simple-icons/simple-icons), released under CC0-1.0.
// Brand marks remain their owners' trademarks; see the Simple Icons DISCLAIMER and each
// brand's guidelines. Per-icon licenses are listed where Simple Icons records one.

export interface BrandIconData {
  title: string
  /** Colore ufficiale del marchio, senza #. */
  hex: string
  /** Path SVG su viewBox 0 0 24 24. */
  path: string
  license?: string
}

export const BRAND_ICONS = {
${body}
} as const satisfies Record<string, BrandIconData>

export type BrandIconSlug = keyof typeof BRAND_ICONS
`

const target = join(import.meta.dirname, '..', 'frontend', 'src', 'lib', 'brandIcons.generated.ts')
writeFileSync(target, output)
console.log(`wrote ${icons.length} icons to ${target}`)
